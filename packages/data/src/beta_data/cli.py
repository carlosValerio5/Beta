"""``beta-data``: seed, ingest and run the medallion pipeline."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

import typer

from beta_data.contracts import CONTRACTS
from beta_data.ingest import ingest_paths
from beta_data.jobs import bronze_to_silver, silver_to_gold
from beta_data.layout import Lakehouse
from beta_data.lineage import RunManifest
from beta_data.seed import seed as seed_lake
from beta_data.tables import read_rows

app = typer.Typer(no_args_is_help=True, help="Beta Climbing medallion lakehouse.")

ROOT = typer.Option(Path("data"), "--root", help="Lakehouse root directory.")
JOBS: dict[str, list[Callable[[Lakehouse], RunManifest]]] = {
    "bronze-to-silver": [bronze_to_silver.run],
    "silver-to-gold": [silver_to_gold.run],
    "all": [bronze_to_silver.run, silver_to_gold.run],
}


@app.command()
def seed(
    count: int = typer.Option(12, help="Number of synthetic walls."),
    start: int = typer.Option(0, help="First seed number."),
    root: Path = ROOT,
) -> None:
    """Generate synthetic walls and run them through the pipeline into bronze."""
    ids = seed_lake(Lakehouse(root), count=count, start=start)
    typer.echo(f"seeded {len(ids)} walls into {root / 'bronze'}")


@app.command()
def ingest(
    paths: list[Path] = typer.Argument(..., exists=True, dir_okay=False),
    device_id: str = typer.Option("ingest"),
    root: Path = ROOT,
) -> None:
    """Add photos to bronze (GPS stripped)."""
    keys = ingest_paths(Lakehouse(root), paths, device_id=device_id)
    for key in keys:
        typer.echo(key)


@app.command()
def run(
    job: str = typer.Argument(..., help="bronze-to-silver | silver-to-gold | all"),
    root: Path = ROOT,
) -> None:
    """Run a medallion job and print its lineage summary."""
    if job not in JOBS:
        raise typer.BadParameter(f"unknown job {job!r}; choose from {', '.join(JOBS)}")
    lake = Lakehouse(root)
    for step in JOBS[job]:
        manifest = step(lake)
        typer.echo(f"{manifest.job} {manifest.run_id}: {len(manifest.inputs)} inputs")
        for out in manifest.outputs:
            typer.echo(f"  {out.table:<18} {out.rows:>6} rows -> {out.path}")


@app.command()
def status(root: Path = ROOT) -> None:
    """Row counts for every silver and gold table."""
    lake = Lakehouse(root)
    for c in CONTRACTS:
        rows = len(read_rows(lake, c.name, layer=c.layer))
        typer.echo(f"{c.layer}/{c.name:<16} v{c.version}  {rows:>6} rows")


@app.command("contracts-doc")
def contracts_doc(out: Path = typer.Option(Path("docs/data/contracts.md"))) -> None:
    """Regenerate the table-contract reference from the contract registry."""
    lines = [
        "# Table contracts",
        "",
        "Generated by `uv run beta-data contracts-doc` from `beta_data.contracts` — do not edit by hand.",
        "Changing a table's columns means a new contract version (see `packages/data/AGENTS.md`).",
        "",
    ]
    for c in CONTRACTS:
        schema = c.arrow_schema()
        lines += [f"## {c.layer}/{c.name} (v{c.version})", "", c.description + ".", ""]
        lines += ["| Column | Type | Nullable |", "|---|---|---|"]
        lines += [f"| `{f.name}` | `{f.type}` | {'yes' if f.nullable else 'no'} |" for f in schema]
        lines.append("")
    lines += [
        "## gold/golden_set.jsonl",
        "",
        "One JSON object per evaluation case: `analysis_id`, `image_sha256`, `image_path`, `width`,",
        "`height`, `px_per_cm`, `problem`, `holds` (detected), `truth_holds`, `truth`, `accepted_beta`.",
        "",
        "## gold/detector_training/coco.json",
        "",
        "COCO detection format; one category per hold colour; boxes from synthetic ground truth.",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    typer.echo(f"wrote {out}")
