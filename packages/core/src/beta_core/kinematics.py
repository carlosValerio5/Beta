"""2D climber kinematics shared by the validators (Python) and the renderer (TypeScript).

Model: a hip point, a torso of fixed length whose axis leans toward the hands, shoulders and hips
spread perpendicular to that axis, and two-bone limbs (upper/lower arm, thigh/shin).

The TypeScript port in ``apps/renderer/src/kinematics.ts`` must produce identical numbers; both sides
are tested against ``contracts/kinematics/fixtures.json`` generated by :func:`kinematics_fixtures`.
"""

from __future__ import annotations

import math
from collections.abc import Mapping, Sequence
from typing import Any

from beta_core.domain.base import DomainModel
from beta_core.domain.beta import Contacts, Limb
from beta_core.domain.climber import BodyModel, ClimberProfile
from beta_core.domain.geometry import Point
from beta_core.domain.holds import Problem

#: How strongly the torso leans toward the hands (0 = always upright, 1 = point straight at them).
TORSO_BLEND = 0.5
#: Which side each limb's middle joint bends to, relative to the root→target direction.
BEND: dict[Limb, int] = {Limb.LH: -1, Limb.RH: 1, Limb.LF: 1, Limb.RF: -1}

_EPS = 1e-9
_UP = (0.0, -1.0)


class IKSolution(DomainModel):
    joint: Point
    end: Point
    reached: bool


def _unit(dx: float, dy: float) -> tuple[float, float]:
    n = math.hypot(dx, dy)
    if n < _EPS:
        return _UP
    return dx / n, dy / n


def torso_axis(hip: Point, hand_targets: Sequence[Point]) -> tuple[float, float]:
    if not hand_targets:
        return _UP
    mx = sum(p.x for p in hand_targets) / len(hand_targets)
    my = sum(p.y for p in hand_targets) / len(hand_targets)
    vx, vy = _unit(mx - hip.x, my - hip.y)
    return _unit(
        TORSO_BLEND * vx + (1 - TORSO_BLEND) * _UP[0], TORSO_BLEND * vy + (1 - TORSO_BLEND) * _UP[1]
    )


def limb_roots(hip: Point, body: BodyModel, hand_targets: Sequence[Point]) -> dict[Limb, Point]:
    """Shoulder and hip joints. The climber faces the wall, so their left is image-left."""
    ax, ay = torso_axis(hip, hand_targets)
    px, py = -ay, ax  # perpendicular, pointing image-right when upright
    sx, sy = hip.x + ax * body.torso, hip.y + ay * body.torso
    hs, hh = body.shoulder_width / 2, body.hip_width / 2
    return {
        Limb.LH: Point(x=sx - px * hs, y=sy - py * hs),
        Limb.RH: Point(x=sx + px * hs, y=sy + py * hs),
        Limb.LF: Point(x=hip.x - px * hh, y=hip.y - py * hh),
        Limb.RF: Point(x=hip.x + px * hh, y=hip.y + py * hh),
    }


def limb_length(body: BodyModel, limb: Limb) -> float:
    return body.arm_length if limb.is_hand else body.leg_length


def segment_lengths(body: BodyModel, limb: Limb) -> tuple[float, float]:
    return (body.upper_arm, body.forearm) if limb.is_hand else (body.thigh, body.shin)


def max_reach_ratio(hip: Point, points: Mapping[Limb, Point | None], body: BodyModel) -> float:
    """Worst (distance / limb length) over limbs in contact. ``<= 1`` means every limb reaches."""
    hands = [p for limb, p in points.items() if p is not None and limb.is_hand]
    roots = limb_roots(hip, body, hands)
    ratios = [
        roots[limb].distance_to(p) / limb_length(body, limb)
        for limb, p in points.items()
        if p is not None
    ]
    return max(ratios, default=0.0)


def best_hip(points: Mapping[Limb, Point | None], body: BodyModel) -> tuple[Point, float]:
    """Hip position minimising :func:`max_reach_ratio` (coarse grid, then local refinement).

    A tiny pull toward the contacts' centroid makes ties deterministic and keeps poses compact.
    """
    present = [p for p in points.values() if p is not None]
    if not present:
        raise ValueError("at least one limb must be in contact")
    cx = sum(p.x for p in present) / len(present)
    cy = sum(p.y for p in present) / len(present)
    span = body.leg_length + body.torso
    centroid = Point(x=cx, y=cy)

    def cost(hip: Point) -> float:
        return max_reach_ratio(hip, points, body) + 1e-3 * hip.distance_to(centroid) / span

    best = centroid
    best_cost = cost(best)

    def search(center: Point, half: float, steps: int) -> None:
        nonlocal best, best_cost
        for i in range(steps):
            for j in range(steps):
                candidate = Point(
                    x=center.x - half + 2 * half * i / (steps - 1),
                    y=center.y - half + 2 * half * j / (steps - 1),
                )
                c = cost(candidate)
                if c < best_cost - _EPS:
                    best, best_cost = candidate, c

    search(centroid, span, 15)
    half = span / 7
    for _ in range(4):
        search(best, half, 7)
        half /= 3
    return best, max_reach_ratio(best, points, body)


#: How extended limbs look in a relaxed climbing position (fraction of full reach).
PREFERRED_HAND_RATIO = 0.85
PREFERRED_FOOT_RATIO = 0.75
#: Legs fold (frog/squat) more freely than arms in a wall-plane projection.
FOOT_WEIGHT = 0.3
HIP_CENTERING = 10.0
GRAVITY = 2.0
#: Limbs folded tighter than this look broken in 2D.
MIN_COMFORT_RATIO = 0.4
FOLD_PENALTY = 5.0


def natural_hip(points: Mapping[Limb, Point | None], body: BodyModel) -> Point:
    """Hip for *showing* a pose: straight-ish arms, bent legs, never beyond full reach.

    :func:`best_hip` answers "is this reachable at all?" (minimax), which crumples the body; route
    videos want the pose a climber would actually hold. Falls back to ``best_hip`` when no
    position reaches every hold.
    """
    compact, worst = best_hip(points, body)
    if worst > 1.0:
        return compact
    span = body.leg_length + body.torso
    in_contact = [(limb, p) for limb, p in points.items() if p is not None]
    mid_x = sum(p.x for _, p in in_contact) / len(in_contact)

    def cost(hip: Point) -> float:
        hands = [p for limb, p in in_contact if limb.is_hand]
        roots = limb_roots(hip, body, hands)
        # Hips stay roughly centred over the holds (no leaning off to one side).
        total = HIP_CENTERING * ((hip.x - mid_x) / span) ** 2
        for limb, p in in_contact:
            ratio = roots[limb].distance_to(p) / limb_length(body, limb)
            if ratio > 1.0:
                return float("inf")
            preferred = PREFERRED_HAND_RATIO if limb.is_hand else PREFERRED_FOOT_RATIO
            total += (1.0 if limb.is_hand else FOOT_WEIGHT) * (ratio - preferred) ** 2
            if ratio < MIN_COMFORT_RATIO:
                total += FOLD_PENALTY * (MIN_COMFORT_RATIO - ratio) ** 2
            # Climbers hang below their hands and stand above their feet.
            below = (p.y - roots[limb].y) if limb.is_hand else (hip.y - p.y)
            if below > 0:
                total += GRAVITY * (below / limb_length(body, limb)) ** 2
        return total

    best, best_cost = compact, cost(compact)
    half = span / 2
    for steps in (15, 7, 7, 7, 7):
        center = best
        for i in range(steps):
            for j in range(steps):
                candidate = Point(
                    x=center.x - half + 2 * half * i / (steps - 1),
                    y=center.y - half + 2 * half * j / (steps - 1),
                )
                c = cost(candidate)
                if c < best_cost - _EPS:
                    best, best_cost = candidate, c
        half /= 3
    return best


def solve_two_bone(root: Point, target: Point, l1: float, l2: float, bend: int) -> IKSolution:
    """Analytic two-bone IK. Unreachable targets stretch the limb straight toward the target."""
    dx, dy = target.x - root.x, target.y - root.y
    d = math.hypot(dx, dy)
    ux, uy = _unit(dx, dy)
    reach = l1 + l2
    if d >= reach:
        joint = Point(x=root.x + ux * l1, y=root.y + uy * l1)
        end = Point(x=root.x + ux * reach, y=root.y + uy * reach)
        reached = d <= reach + _EPS
        return IKSolution(joint=joint, end=target if reached else end, reached=reached)
    min_reach = abs(l1 - l2)
    dd = max(d, min_reach)
    a = (l1 * l1 - l2 * l2 + dd * dd) / (2 * dd) if dd > _EPS else 0.0
    h = math.sqrt(max(l1 * l1 - a * a, 0.0))
    px, py = -uy, ux
    joint = Point(x=root.x + ux * a + px * h * bend, y=root.y + uy * a + py * h * bend)
    if d >= min_reach - _EPS:
        return IKSolution(joint=joint, end=target, reached=True)
    return IKSolution(joint=joint, end=Point(x=root.x + ux * dd, y=root.y + uy * dd), reached=False)


def contact_points(problem: Problem, contacts: Contacts) -> dict[Limb, Point | None]:
    """Hold centres for each limb in contact (raises ``UnknownHoldError`` for bad IDs)."""
    return {
        limb: (problem.hold(hold_id).center if hold_id is not None else None)
        for limb, hold_id in contacts.items()
    }


# ---------------------------------------------------------------- cross-language fixtures


def _pt(p: Point) -> dict[str, float]:
    return {"x": round(p.x, 6), "y": round(p.y, 6)}


def kinematics_fixtures() -> dict[str, Any]:
    """Golden cases the TypeScript renderer must reproduce exactly (to 1e-6)."""
    two_bone_cases = [
        (Point(x=0, y=0), Point(x=3, y=4), 3.0, 3.0, 1),
        (Point(x=0, y=0), Point(x=3, y=4), 3.0, 3.0, -1),
        (Point(x=0, y=0), Point(x=10, y=0), 3.0, 3.0, 1),
        (Point(x=1, y=1), Point(x=1, y=1), 3.0, 2.0, 1),
        (Point(x=100, y=200), Point(x=160, y=90), 80.0, 70.0, -1),
        (Point(x=0, y=0), Point(x=0.5, y=0), 3.0, 1.0, 1),
    ]
    two_bone = []
    for root, target, l1, l2, bend in two_bone_cases:
        sol = solve_two_bone(root, target, l1, l2, bend)
        two_bone.append(
            {
                "root": _pt(root),
                "target": _pt(target),
                "l1": l1,
                "l2": l2,
                "bend": bend,
                "joint": _pt(sol.joint),
                "end": _pt(sol.end),
                "reached": sol.reached,
            }
        )

    body = BodyModel.from_profile(ClimberProfile(height_cm=175)).scaled(3.0)
    hip = Point(x=500, y=1000)
    roots_cases: list[list[Point]] = [
        [],
        [Point(x=900, y=800)],
        [Point(x=450, y=700), Point(x=560, y=690)],
    ]
    limb_roots_out = []
    for hands in roots_cases:
        roots = limb_roots(hip, body, hands)
        limb_roots_out.append(
            {
                "hip": _pt(hip),
                "hand_targets": [_pt(p) for p in hands],
                "roots": {limb.value: _pt(p) for limb, p in roots.items()},
            }
        )

    return {
        "version": 1,
        "torso_blend": TORSO_BLEND,
        "bend": {limb.value: sign for limb, sign in BEND.items()},
        "body": {
            k: (round(v, 6) if isinstance(v, float) else v) for k, v in body.model_dump().items()
        },
        "two_bone": two_bone,
        "limb_roots": limb_roots_out,
    }
